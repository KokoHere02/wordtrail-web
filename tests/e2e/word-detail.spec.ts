import { expect, test } from '@playwright/test';

test('read, browse across book pages and return to the original list', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 1360, height: 900 });
  await page.goto('/login');
  await page.getByLabel('手机号或邮箱').fill('13800138000');
  await page.getByLabel('密码', { exact: true }).fill('example123');
  await page.getByRole('button', { name: '登录', exact: true }).click();
  await page.waitForURL(url => !url.pathname.includes('login'));
  await page.evaluate(async () => {
    const apiPath = '/src/api/http.ts', routerPath = '/src/router/index.ts';
    const { http } = await import(/* @vite-ignore */ apiPath);
    const original = http.defaults.adapter;
    http.defaults.adapter = async (config: { url: string }) => {
      if (config.url === '/learning/settings') return { config, status: 200, headers: {}, data: { code: 'OK', data: { pronunciation: { autoPlay: false, accent: 'US', playbackRate: 1, repeatCount: 1 } } } };
      if (config.url === '/sentence-practice/sentences') return { config, status: 200, headers: {}, data: { code: 'OK', data: [{ id: 1, englishText: `The word is “${Reflect.get(window, 'sampleHeadword')}”.`, referenceTranslation: '这个词出现在例句中。', learning: false }] } };
      return original(config);
    };
    const { router } = await import(/* @vite-ignore */ routerPath);
    await router.push('/books/1');
  });
  await page.getByRole('button', { name: '未学', exact: true }).click();
  await page.getByRole('button', { name: '下一页', exact: true }).click();
  const first = page.locator('.preview-word-row a').first();
  const entry = await first.innerText();
  await page.evaluate(word => Reflect.set(window, 'sampleHeadword', word), entry);
  await first.click();
  await expect(page).toHaveURL(/book=1.*page=2.*status=UNLEARNED/);
  await expect(page.getByRole('heading', { name: entry, exact: true })).toBeVisible();
  const example = page.locator('.word-sentence-row p[lang=en]');
  await expect(example).toHaveText(`The word is “${entry}”.`);
  await expect(example).toHaveCSS('font-weight', '500');
  await expect(example.locator('strong')).toHaveText(entry);
  await expect(example.locator('strong')).toHaveCSS('font-weight', '700');
  await expect(page.locator('.word-detail-translation')).toHaveCSS('font-weight', '400');
  const heading = page.getByRole('heading', { name: entry, exact: true });
  await expect(heading).toHaveCSS('font-family', /^Nunito,/);
  await expect(heading).toHaveCSS('font-weight', '800');
  expect(await page.evaluate(async () => (await document.fonts.load('800 32px Nunito', 'accurate')).length)).toBeGreaterThan(0);
  await page.getByRole('button', { name: '学习计划', exact: true }).click();
  await expect(page.getByText('尚未加入长期学习计划。')).toBeVisible();
  await page.getByRole('button', { name: '学习历史', exact: true }).click();
  await expect(page.getByRole('button', { name: '默写记录' })).toBeVisible();
  await page.getByRole('button', { name: '关联例句', exact: true }).click();
  await page.getByRole('button', { name: '上一个单词' }).click();
  await expect(page).toHaveURL(/book=1.*page=1/);
  await page.getByRole('button', { name: '下一个单词' }).click();
  await expect(page.getByRole('heading', { name: entry, exact: true })).toBeVisible();
  const listButton = page.getByRole('button', { name: '词表', exact: true });
  const desktopList = page.getByRole('complementary', { name: '词表' });
  await expect(desktopList.getByRole('combobox')).toHaveValue('1');
  await expect(desktopList.locator('option:checked')).toHaveText('四级核心词汇');
  await expect(desktopList.getByText('第 2 页 · 本页单词')).toBeVisible();
  await expect(desktopList.locator('li')).toHaveCount(10);
  await expect(desktopList.locator('[aria-current=page]')).toContainText(entry);
  await page.getByRole('button', { name: '切换浅色主题' }).click();
  await page.screenshot({ path: testInfo.outputPath('word-detail-desktop.png'), animations: 'disabled' });
  await page.getByRole('button', { name: '收起词表' }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await listButton.click();
  const sheet = page.getByRole('dialog', { name: '词本词表' });
  await expect(sheet.locator('li')).toHaveCount(10);
  await expect(sheet.locator('li strong').first()).toHaveCSS('font-family', /^Nunito,/);
  await expect.poll(async () => {
    const rect = await sheet.boundingBox();
    return rect ? Math.abs(rect.y + rect.height - 844) : 844;
  }).toBeLessThan(2);
  await page.screenshot({ path: testInfo.outputPath('word-detail-mobile-list.png') });
  const target = sheet.locator('li button').nth(1);
  const nextWord = await target.locator('strong').innerText();
  await target.click();
  await expect(sheet).toHaveCount(0);
  await expect(page.getByRole('heading', { name: nextWord, exact: true })).toBeVisible();
  expect(await page.locator('html').evaluate(el => el.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath('word-detail-mobile.png') });
  await page.getByRole('button', { name: '返回', exact: true }).click();
  await expect(page).toHaveURL(/\/books\/1$/);
  await expect(first).toHaveText(entry);
  await expect(page.getByRole('button', { name: '未学', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await page.evaluate(async () => {
    const module = '/src/router/index.ts';
    const { router } = await import(/* @vite-ignore */ module);
    await router.push('/words/1021');
  });
  await listButton.click();
  const directBook = page.getByRole('dialog', { name: '词本词表' });
  await expect(directBook.getByText('第 3 页 · 本页单词')).toBeVisible();
  await expect(directBook.locator('button[aria-current="page"]')).toHaveCount(1);
  await directBook.getByRole('combobox').selectOption('');
  const dictionary = page.getByRole('dialog', { name: '词库检索' });
  await dictionary.getByRole('searchbox').fill('acc');
  await dictionary.getByRole('button', { name: '搜索', exact: true }).click();
  const match = dictionary.locator('li button').first();
  const word = await match.locator('strong').innerText();
  await match.click();
  await expect(page.getByRole('heading', { name: word, exact: true })).toBeVisible();
});
